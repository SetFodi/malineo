/** The step with its words in the chosen language. Demo data is untouched. */
export function localize(step: Step, lang: Lang): Step {
  if (lang === 'en') return step;
  const ka = KA[step.id];
  if (!ka) return step;
  return {
    ...step,
    title: ka.title,
    body: ka.body,
    was: ka.was ?? step.was,
    aside: ka.aside ?? step.aside,
    list: step.list?.map((item, i) => ({ ...item, label: ka.list?.[i] ?? item.label })),
    tryIt: step.tryIt && { ...step.tryIt, prompt: ka.tryPrompt ?? step.tryIt.prompt, done: ka.tryDone ?? step.tryIt.done },
  };
}
